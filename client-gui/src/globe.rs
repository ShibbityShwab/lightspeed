//! Orthographic globe for the route visualiser.
//!
//! Draws the relay fleet on a sphere with the active relay highlighted, so the
//! window can answer "where does my traffic egress" at a glance. Deliberately
//! dependency-free: an orthographic projection onto egui's painter is a few
//! dozen lines and works on every platform, where pulling in a 3D engine (or a
//! webview) for one wireframe would cost far more than it returns.
//!
//! Coordinates come from the registry node id, which already encodes the city
//! (`relay-lax-1`, `relay-fra`), so no geo database is needed for the fleet.
//! Placing an arbitrary game server would need IP geolocation, which this
//! module does not have.

use eframe::egui::{self, Color32, Pos2, Stroke};

/// Latitude/longitude in degrees.
pub type LatLon = (f32, f32);

/// Coordinates for a registry node id, matched on its city segment.
pub fn relay_coords(node_id: &str) -> Option<LatLon> {
    let id = node_id.to_ascii_lowercase();
    let table: [(&str, LatLon); 8] = [
        ("lax", (34.05, -118.24)),
        ("ewr", (40.74, -74.17)),
        ("sgp", (1.35, 103.82)),
        ("fra", (50.11, 8.68)),
        ("nrt", (35.68, 139.69)),
        ("bom", (19.08, 72.88)),
        ("mad", (40.42, -3.70)),
        ("syd", (-33.87, 151.21)),
    ];
    table
        .iter()
        .find(|(code, _)| id.contains(code))
        .map(|(_, ll)| *ll)
}

/// A point to plot: coordinates, colour, and label.
pub struct Marker {
    pub at: LatLon,
    pub colour: Color32,
    pub label: String,
}

/// Natural Earth 110m land, generated by infra/scripts/build-world-outline.py.
const LAND: &[u8] = include_bytes!("../data/world-land.bin");

/// Read a little-endian u16, or `None` at the end of a truncated buffer.
fn u16_at(b: &[u8], o: usize) -> Option<usize> {
    let hi = *b.get(o)? as usize;
    let lo = *b.get(o + 1)? as usize;
    Some(hi | (lo << 8))
}

/// Draw an equirectangular map of the world with the same markers and route.
///
/// The globe answers "where is my relay" but costs a third of the card and needs
/// the reader to imagine the far hemisphere. A flat map is legible at a glance,
/// uses the window's width instead of its height, and reuses the same Natural
/// Earth coastline blob.
pub fn draw_map(
    ui: &mut egui::Ui,
    width: f32,
    height: f32,
    markers: &[Marker],
    route: Option<(LatLon, LatLon)>,
) {
    let (rect, _) = ui.allocate_exact_size(egui::Vec2::new(width, height), egui::Sense::hover());
    let painter = ui.painter_at(rect);

    let bg = Color32::from_rgb(0x11, 0x11, 0x18);
    let grid = Color32::from_rgb(0x22, 0x22, 0x30);
    let land = Color32::from_rgb(0x4A, 0x4A, 0x72);
    painter.rect_filled(rect, egui::CornerRadius::same(6), bg);

    // Equirectangular: lon -180..180 across, lat 90..-90 down.
    let at = |(lat, lon): LatLon| -> Pos2 {
        Pos2::new(
            rect.left() + (lon + 180.0) / 360.0 * rect.width(),
            rect.top() + (90.0 - lat) / 180.0 * rect.height(),
        )
    };

    for i in 1..6 {
        let x = rect.left() + rect.width() * i as f32 / 6.0;
        painter.line_segment(
            [Pos2::new(x, rect.top()), Pos2::new(x, rect.bottom())],
            Stroke::new(1.0, grid),
        );
    }
    for i in 1..3 {
        let y = rect.top() + rect.height() * i as f32 / 3.0;
        painter.line_segment(
            [Pos2::new(rect.left(), y), Pos2::new(rect.right(), y)],
            Stroke::new(1.0, grid),
        );
    }

    // The same coastline blob the globe walks, bounds-checked the same way.
    if let Some(polys) = u16_at(LAND, 0) {
        let stroke = Stroke::new(1.0, land);
        let mut o = 2usize;
        for _ in 0..polys {
            let Some(count) = u16_at(LAND, o) else {
                break;
            };
            o += 2;
            let mut run: Vec<Pos2> = Vec::with_capacity(count);
            for _ in 0..count {
                let (Some(a), Some(b)) = (u16_at(LAND, o), u16_at(LAND, o + 2)) else {
                    break;
                };
                o += 4;
                run.push(at((a as i16 as f32 / 100.0, b as i16 as f32 / 100.0)));
            }
            if run.len() > 1 {
                painter.add(egui::Shape::line(run, stroke));
            }
        }
    }

    if let Some((from, to)) = route {
        painter.line_segment(
            [at(from), at(to)],
            Stroke::new(1.5, Color32::from_rgb(0x6C, 0x5C, 0xE7)),
        );
    }

    for (i, marker) in markers.iter().enumerate() {
        let p = at(marker.at);
        // A white core with a coloured ring reads against the dark land and the
        // graticule; a flat coloured dot did not at this size.
        painter.circle_filled(p, 3.5, Color32::WHITE);
        painter.circle_stroke(p, 5.5, Stroke::new(1.5, marker.colour));
        // No permanent label at 320 px - they overlapped into noise - but the
        // name is one hover away, and the ledger under the map spells it out.
        let hit = egui::Rect::from_center_size(p, egui::Vec2::splat(14.0));
        ui.interact(
            hit,
            egui::Id::unique(("map-marker", i)),
            egui::Sense::hover(),
        )
        .on_hover_text(&marker.label);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_truncated_land_blob_does_not_panic() {
        // Pins the bounds checks in the land walk. The blob is generated and
        // committed, so a truncated regeneration is the realistic failure; an
        // out-of-range index here would panic inside the paint loop.
        for cut in [0usize, 1, 2, 5, 9, 33, LAND.len() / 2] {
            assert!(u16_at(&LAND[..cut.min(LAND.len())], 0).is_none() || cut >= 2);
        }
        let empty: &[u8] = &[];
        assert_eq!(
            u16_at(empty, 0),
            None,
            "reading past an empty blob must not panic"
        );
    }

    #[test]
    fn the_land_blob_is_well_formed_end_to_end() {
        let polys = u16_at(LAND, 0).expect("polygon count");
        assert!(polys > 100, "only {polys} polygons; blob looks truncated");

        let mut o = 2usize;
        let mut points = 0usize;
        for _ in 0..polys {
            let count = u16_at(LAND, o).expect("point count");
            o += 2;
            points += count;
            o += count * 4;
            assert!(o <= LAND.len(), "blob runs out mid-polygon at offset {o}");
        }
        assert_eq!(o, LAND.len(), "trailing bytes after the last polygon");
        assert!(points > 1000, "only {points} points; blob looks truncated");
    }

    #[test]
    fn city_codes_map_to_coordinates() {
        assert!(relay_coords("relay-lax-1").is_some());
        assert!(relay_coords("relay-fra").is_some());
        assert!(relay_coords("relay-syd-1").is_some());
    }

    #[test]
    fn unknown_ids_have_no_position() {
        assert!(relay_coords("my-custom-proxy").is_none());
        assert!(relay_coords("").is_none());
    }
}
