//! Equirectangular telemetry map for the route surface.
//!
//! Direction C draws the shipped Natural Earth 110m land as a **precomputed dot
//! cloud** (the polygon mask is evaluated once per map size and cached; no
//! per-frame polygon test), a graticule, the eight real fleet coordinates as
//! small crosses, and the active relay as a haloed ring with its city code. It
//! draws no game-server point: the client only knows the relay city
//! (`docs/design/gui-c-token-sheet.md` §3/§4.4), so nothing on this map is
//! fabricated.
//!
//! The coordinate table comes from the registry node id, which already encodes
//! the city (`relay-lax-1`, `relay-fra`), so no geo database is needed.

use std::sync::{Arc, Mutex, OnceLock};

use eframe::egui::{self, Color32, Pos2, Rect, Stroke};

use crate::app::a11y::AccessKitResponse;
use crate::design::{
    accent_text, border_1, grid, ice, map_bg, map_fleet, map_halo, map_halo_fill, map_land,
    on_accent, R_PANEL, S4, TRACK_FLEET,
};

/// Latitude/longitude in degrees.
pub type LatLon = (f32, f32);

/// Coordinates for a registry node id, matched on its city segment.
pub fn relay_coords(node_id: &str) -> Option<LatLon> {
    let id = node_id.to_ascii_lowercase();
    let table: [(&str, LatLon); 8] = [
        ("lax", (34.05, -118.24)),
        ("ewr", (40.74, -74.17)),
        ("sgp", (1.35, 103.82)),
        ("fra", (50.11, 8.68)),
        ("nrt", (35.68, 139.69)),
        ("bom", (19.08, 72.88)),
        ("mad", (40.42, -3.70)),
        ("syd", (-33.87, 151.21)),
    ];
    table
        .iter()
        .find(|(code, _)| id.contains(code))
        .map(|(_, ll)| *ll)
}

/// A point to plot: coordinates, colour, and label.
pub struct Marker {
    pub at: LatLon,
    pub colour: Color32,
    pub label: String,
}

/// Natural Earth 110m land, generated by infra/scripts/build-world-outline.py.
const LAND: &[u8] = include_bytes!("../data/world-land.bin");

/// The map's crop, tuned for the 320 px window (drop the empty polar bands).
const LAT_TOP: f32 = 82.0;
const LAT_BOTTOM: f32 = -58.0;
const LON_LEFT: f32 = -172.0;
const LON_RIGHT: f32 = 178.0;

/// Read a little-endian u16, or `None` at the end of a truncated buffer.
fn u16_at(b: &[u8], o: usize) -> Option<usize> {
    let hi = *b.get(o)? as usize;
    let lo = *b.get(o + 1)? as usize;
    Some(hi | (lo << 8))
}

/// One land polygon ring as `(lat, lon)` degrees.
fn land_rings() -> &'static [Vec<LatLon>] {
    static RINGS: OnceLock<Vec<Vec<LatLon>>> = OnceLock::new();
    RINGS.get_or_init(|| {
        let count = u16_at(LAND, 0).unwrap_or(0);
        let mut offset = 2usize;
        let mut rings: Vec<Vec<LatLon>> = Vec::with_capacity(count);
        for _ in 0..count {
            let Some(n) = u16_at(LAND, offset) else {
                break;
            };
            offset += 2;
            let mut ring = Vec::with_capacity(n);
            let mut complete = true;
            for _ in 0..n {
                let (Some(hi), Some(lo)) = (u16_at(LAND, offset), u16_at(LAND, offset + 2)) else {
                    complete = false;
                    break;
                };
                offset += 4;
                ring.push((hi as i16 as f32 / 100.0, lo as i16 as f32 / 100.0));
            }
            if complete && ring.len() > 2 {
                rings.push(ring);
            }
        }
        rings
    })
}

/// Point-in-polygon (even-odd), on the lon/lat plane.
fn point_in_ring(lon: f32, lat: f32, ring: &[LatLon]) -> bool {
    // `ring` points are (lat, lon) in blob order; the polygon test is on the
    // (lon, lat) plane.
    let mut inside = false;
    let mut j = ring.len() - 1;
    for i in 0..ring.len() {
        let (lat_i, lon_i) = ring[i];
        let (lat_j, lon_j) = ring[j];
        if (lat_i > lat) != (lat_j > lat)
            && lon < (lon_j - lon_i) * (lat - lat_i) / (lat_j - lat_i) + lon_i
        {
            inside = !inside;
        }
        j = i;
    }
    inside
}

/// Project a lon/lat point into a map rect.
fn project(lon: f32, lat: f32, rect: Rect) -> Pos2 {
    let x = (lon - LON_LEFT) / (LON_RIGHT - LON_LEFT) * rect.width();
    let y = (LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM) * rect.height();
    Pos2::new(rect.left() + x, rect.top() + y)
}

/// Paint tracked text (egui has no letter-spacing), returning the painted width.
fn paint_tracked(
    painter: &egui::Painter,
    at: Pos2,
    align: egui::Align2,
    text: &str,
    font: &egui::FontId,
    color: Color32,
    tracking_em: f32,
) -> f32 {
    let tracking = tracking_em * font.size;
    let mut width = 0.0;
    for (i, ch) in text.chars().enumerate() {
        if i > 0 {
            width += tracking;
        }
        let galley = painter.layout_no_wrap(ch.to_string(), font.clone(), color);
        width += galley.size().x;
    }
    let height = painter
        .layout_no_wrap(text.to_string(), font.clone(), color)
        .size()
        .y;
    let rect = align.anchor_size(at, egui::vec2(width, height));
    let mut x = rect.left();
    for ch in text.chars() {
        let galley = painter.layout_no_wrap(ch.to_string(), font.clone(), color);
        let w = galley.size().x;
        painter.galley(Pos2::new(x, rect.top()), galley, color);
        x += w + tracking;
    }
    width
}

/// The land dots for one map size, cached as a shared `Arc` (the sheet requires
/// a single precomputed batch, not a per-frame polygon scan).
type DotCloud = Arc<Vec<(f32, f32)>>;
type DotCache = std::sync::Mutex<Vec<((u32, u32), DotCloud)>>;

fn land_dots(width: u32, height: u32, pitch: f32) -> DotCloud {
    static CACHE: OnceLock<DotCache> = OnceLock::new();
    let cache = CACHE.get_or_init(|| Mutex::new(Vec::new()));
    let key = (width, height);
    {
        let guard = cache.lock().expect("telemetry dot cache poisoned");
        if let Some((_, dots)) = guard.iter().find(|(k, _)| *k == key) {
            return Arc::clone(dots);
        }
    }
    let rings = land_rings();
    let mut dots = Vec::new();
    let mut y = pitch * 0.5;
    while y <= height as f32 {
        let mut x = pitch * 0.5;
        while x <= width as f32 {
            let lon = LON_LEFT + x / width as f32 * (LON_RIGHT - LON_LEFT);
            let lat = LAT_TOP - y / height as f32 * (LAT_TOP - LAT_BOTTOM);
            if rings.iter().any(|ring| point_in_ring(lon, lat, ring)) {
                dots.push((x, y));
            }
            x += pitch;
        }
        y += pitch;
    }
    let dots = Arc::new(dots);
    let mut guard = cache.lock().expect("telemetry dot cache poisoned");
    if let Some((_, cached)) = guard.iter().find(|(k, _)| *k == key) {
        return Arc::clone(cached);
    }
    guard.push((key, Arc::clone(&dots)));
    dots
}

/// Draw the Direction C telemetry map (token sheet §3/§4.4).
///
/// `height` is the sheet's 146 normal / 96 compact band (`MAP_H` /
/// `MAP_H_COMPACT`); the map fills the width it is given.
pub fn draw_telemetry_map(
    ui: &mut egui::Ui,
    width: f32,
    height: f32,
    markers: &[Marker],
    description: &str,
) -> egui::Response {
    let (rect, response) = ui.allocate_exact_size(egui::vec2(width, height), egui::Sense::hover());
    // The map is a canvas: a screen reader cannot read its dots, so it is
    // reported as one Image named by the caller's localized description, and
    // automation reaches it by a stable id.
    let response = response
        .a11y_widget(egui::accesskit::Role::Image, true, description)
        .a11y_automation_id(crate::app::a11y::automation::ROUTE_MAP);
    let painter = ui.painter_at(rect);

    // Panel: map background + 1 px rule + 3 px radius (flat; no shadow).
    painter.rect(
        rect,
        egui::CornerRadius::same(R_PANEL),
        map_bg,
        Stroke::new(1.0, border_1),
        egui::StrokeKind::Inside,
    );

    // Graticule: verticals at w/6, horizontals at h/3.
    for i in 1..6 {
        let px = rect.left() + rect.width() * i as f32 / 6.0;
        painter.line_segment(
            [Pos2::new(px, rect.top()), Pos2::new(px, rect.bottom())],
            Stroke::new(1.0, grid),
        );
    }
    for i in 1..3 {
        let py = rect.top() + rect.height() * i as f32 / 3.0;
        painter.line_segment(
            [Pos2::new(rect.left(), py), Pos2::new(rect.right(), py)],
            Stroke::new(1.0, grid),
        );
    }

    // Land: the cached dot cloud, one batch, 0.85 px radius.
    let pitch = if height <= 100.0 { 5.0 } else { 5.6 };
    let inner = rect.shrink(1.0);
    let dots = land_dots(
        rect.width().round() as u32,
        rect.height().round() as u32,
        pitch,
    );
    for &(dx, dy) in dots.iter() {
        let at = Pos2::new(inner.left() + dx, inner.top() + dy);
        if inner.contains(at) {
            painter.circle_filled(at, 0.85, map_land);
        }
    }

    // Fleet crosses; the active relay (ice colour) is a haloed ring + code.
    let active = markers.iter().find(|m| m.colour == accent_text);
    for marker in markers {
        if marker.colour == accent_text {
            continue;
        }
        let at = project(marker.at.1, marker.at.0, inner);
        painter.line_segment(
            [Pos2::new(at.x - 2.6, at.y), Pos2::new(at.x + 2.6, at.y)],
            Stroke::new(1.0, map_fleet),
        );
        painter.line_segment(
            [Pos2::new(at.x, at.y - 2.6), Pos2::new(at.x, at.y + 2.6)],
            Stroke::new(1.0, map_fleet),
        );
    }
    if let Some(marker) = active {
        let at = project(marker.at.1, marker.at.0, inner);
        painter.circle_filled(at, 8.0, map_halo_fill);
        painter.circle_stroke(at, 8.0, Stroke::new(1.0, map_halo));
        painter.circle_filled(at, 2.2, ice);
        let code = marker
            .label
            .split(['-', '·'])
            .next()
            .map(str::trim)
            .filter(|code| !code.is_empty())
            .unwrap_or(marker.label.as_str())
            .to_uppercase();
        let font = egui::FontId::new(crate::design::CAPTION, egui::FontFamily::Monospace);
        let label_w = {
            let tracking = TRACK_FLEET * font.size;
            let mut w = 0.0;
            for (i, ch) in code.chars().enumerate() {
                if i > 0 {
                    w += tracking;
                }
                w += painter
                    .layout_no_wrap(ch.to_string(), font.clone(), ice)
                    .size()
                    .x;
            }
            w
        };
        let label_at = Pos2::new((at.x + 11.0).min(rect.right() - S4 - label_w), at.y - 14.0);
        paint_tracked(
            &painter,
            label_at,
            egui::Align2::LEFT_CENTER,
            &code,
            &font,
            ice,
            TRACK_FLEET,
        );
        let _ = on_accent;
        return response.on_hover_text(marker.label.clone());
    }
    let _ = on_accent;
    response
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_land_blob_is_well_formed() {
        let rings = land_rings();
        assert!(rings.len() > 10, "only {} land rings", rings.len());
        let points: usize = rings.iter().map(|ring| ring.len()).sum();
        assert!(points > 1000, "only {points} points; blob looks truncated");
    }

    #[test]
    fn city_codes_map_to_coordinates() {
        assert!(relay_coords("relay-lax-1").is_some());
        assert!(relay_coords("relay-fra").is_some());
        assert!(relay_coords("relay-syd-1").is_some());
    }

    #[test]
    fn unknown_ids_have_no_position() {
        assert!(relay_coords("my-custom-proxy").is_none());
        assert!(relay_coords("").is_none());
    }

    #[test]
    fn the_dot_cloud_is_deterministic_and_cached() {
        let first = land_dots(288, 146, 5.6);
        let second = land_dots(288, 146, 5.6);
        assert!(!first.is_empty(), "the land mask produced no dots");
        assert!(
            Arc::ptr_eq(&first, &second),
            "the dot cloud was rebuilt instead of cached"
        );
        // The mask is land-only: every dot falls inside a ring.
        let rings = land_rings();
        for &(x, y) in first.iter().take(20) {
            let lon = LON_LEFT + x / 288.0 * (LON_RIGHT - LON_LEFT);
            let lat = LAT_TOP - y / 146.0 * (LAT_TOP - LAT_BOTTOM);
            assert!(rings.iter().any(|ring| point_in_ring(lon, lat, ring)));
        }
    }
}
