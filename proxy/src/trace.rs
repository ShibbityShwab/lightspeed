//! Relay-side TTL traceroute: the last responsive hop on the relay→server path.
//!
//! Design: `docs/design/relay-server-leg.md` and `docs/design/relay-selection-sota.md`
//! (§4, fallback 2). When a hosting-network server does not answer ICMP, the
//! relay's measured server leg is "unknown"; a TTL-limited trace still bounds
//! the path - the last router that answered is a **placement anchor** for a
//! server whose geo data is wrong or absent. What this module does **not**
//! provide is a city: turning a hop address into a place needs hop geolocation
//! data the product does not have, so the result is reported as "the path
//! reaches <router>" and never as a location claim.
//!
//! ## Unprivileged, like the server-leg prober
//!
//! The relay unit has no `CAP_NET_RAW` (see `proxy/src/ping.rs`). The primary
//! mechanism is an ordinary unprivileged UDP socket:
//!
//! * one fresh socket per probe, with `IP_TTL` set to the hop being measured
//!   and `IP_RECVERR` enabled;
//! * the kernel queues every ICMP error for the socket, and `recvmsg(...,
//!   MSG_ERRQUEUE)` reads the ICMP type/code plus the **offender** address
//!   (the router that generated the error) from the `IP_RECVERR` control
//!   message;
//! * an ICMP time-exceeded is one router, a port-unreachable generated by the
//!   destination itself means the trace is complete.
//!
//! If the UDP error queue cannot be set up (`IP_RECVERR` refused, socket
//! unavailable), the prober falls back to the unprivileged ICMP echo socket
//! the server-leg prober already uses, with the same TTL and error-queue read:
//! a router's time-exceeded is the same control message, and an echo reply is
//! the complete signal. If neither works the trace degrades to `None` - never
//! a panic, never a fabricated hop.
//!
//! ## The gates are the deliverable
//!
//! A relay sending TTL-limited packets to client-named addresses is a scanning
//! surface, so every bound below is load-bearing rather than defensive polish:
//!
//! * Only an address a **live session has already forwarded to** is ever
//!   traced - the same [`FORWARD_THRESHOLD`] gate as the server-leg prober,
//!   and the target comes from the data path only.
//! * Only a **public unicast** destination is probed ([`is_probeable`]);
//!   private, loopback, link-local, CGNAT, benchmarking and reserved ranges are
//!   refused.
//! * At most [`MAX_HOPS`] TTLs, at most [`PROBES_PER_HOP`] probes per TTL, one
//!   second per probe, and an **empty payload** - the probe is never shaped
//!   like game traffic and never carries a game-protocol payload.
//! * One trace per server per [`TRACE_INTERVAL`] (5 min) and a cached result is
//!   reportable for [`TRACE_CACHE_TTL`] (10 min), so a hundred sessions to one
//!   server cost one trace.
//! * A **global cap** of [`MAX_TRACES_PER_MINUTE`] traces, whether or not the
//!   per-server cadence would allow more.
//! * Every probe is charged through the relay's egress budget guard before it
//!   is sent ([`BudgetGuard::try_charge_probe`]); a refused charge ends the
//!   trace and the partial result is **discarded**, not reported, and counted
//!   as denied. Probe traffic therefore counts against the same ceiling as
//!   relayed traffic.
//! * The prober never runs on an async worker: the trace thread blocks for up
//!   to `MAX_HOPS × HOP_TIMEOUT` and is detached for the process lifetime.

