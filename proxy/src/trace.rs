/// Upper bound on measured hops; matches the protocol's client-side ceiling.
pub const MAX_HOPS: u8 = MAX_SERVER_TRACE_HOPS;

/// Probes per TTL. A second probe is only sent when the first timed out, so a
/// healthy path costs one probe per hop and a lossy hop gets one retry.
pub const PROBES_PER_HOP: u8 = 2;

/// How long one TTL probe waits for its ICMP answer.
pub const HOP_TIMEOUT: Duration = Duration::from_secs(1);

/// Cadence per active server. A trace is slow (up to `MAX_HOPS × HOP_TIMEOUT`),
/// and the answer it produces - the last router - changes on a route-change
/// scale, not a latency scale.
pub const TRACE_INTERVAL: Duration = Duration::from_secs(300);

/// How long a completed trace stays reportable. Ten minutes is two trace
/// intervals: a cached path remains honest across one missed cadence.
pub const TRACE_CACHE_TTL: Duration = Duration::from_secs(600);

/// Global cap on traces started per minute, independent of the per-server
/// cadence. Bounds a bug or a flood of fresh servers; when the cap binds, new
/// servers simply stay untraced (the ranking falls back to its bounds).
pub const MAX_TRACES_PER_MINUTE: u32 = 1;

/// Minimum interval between reports for one control session.
pub const REPORT_INTERVAL: Duration = Duration::from_secs(5);

/// How long a registered interest stays live without a refreshed forward.
pub const INTEREST_TTL: Duration = Duration::from_secs(60);

/// Timer resolution of the background trace thread.
pub const TRACE_TICK: Duration = Duration::from_secs(1);

/// Egress charged to the budget for one probe.
///
/// The on-wire cost is one tiny UDP datagram (28 B IP+UDP header plus the empty
/// payload), or one 8-byte ICMP echo. The estimate deliberately rounds up: the
/// budget is a ceiling, and under-counting measurement traffic is the failure
/// this charge exists to prevent.
pub const PROBE_EGRESS_BYTES: u64 = 64;

/// Largest believable last-hop round trip, microseconds (5 s). A router further
/// away than this did not answer; the reply is a stale or misread error.
pub const MAX_LAST_HOP_RTT_US: u32 = 5_000_000;

/// Upper bound on distinct control-session interests tracked at once.
const MAX_INTERESTS: usize = 4_096;

/// Upper bound on per-server trace state, so the cache cannot grow with every
/// server ever seen.
const MAX_TRACE_SERVERS: usize = 512;

/// Trace probe payload: **empty** on purpose.
///
/// A traceroute probe must never look like a game packet. There is no payload
/// to mistake for a game protocol, no magic string a server could parse as a
/// query, and the datagram is the smallest one IPv4/UDP can carry.
pub const TRACE_PROBE_PAYLOAD: &[u8] = b"";

/// One TTL probe's outcome, from a scripted prober in tests or the socket layer
/// on a relay.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProbeOutcome {
    /// An intermediate router answered with an ICMP error (time-exceeded, or an
    /// unreachable it generated). `rtt_us` is the time since the probe was sent.
    Router {
        /// The router that generated the answer.
        responder: Ipv4Addr,
        /// Round trip to that router, microseconds.
        rtt_us: u32,
    },
    /// The destination itself answered: an ICMP port-unreachable for a UDP
    /// probe, or an echo reply for the ICMP fallback. The trace is complete.
    Destination,
    /// Nothing matched before [`HOP_TIMEOUT`].
    Timeout,
    /// The probe was not sent because the egress budget refused its charge.
    /// Ends the trace.
    Denied,
}

/// The measured path to one game server.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Trace {
    /// Highest TTL that produced any reply: the distance in hops to
    /// [`Self::last_hop`], or to the destination when [`Self::complete`].
    pub hops: u8,
    /// The router that answered at the highest TTL below the destination (the
    /// penultimate router of the measured path). `None` when no router answered.
    pub last_hop: Option<Ipv4Addr>,
    /// Round trip to [`Self::last_hop`], microseconds. `None` exactly when
    /// `last_hop` is `None`.
    pub last_hop_rtt_us: Option<u32>,
    /// Whether the destination itself answered. An incomplete trace is still a
    /// truthful bound: the path reaches at least `last_hop`.
    pub complete: bool,
}

/// Tunables for one trace. Defaults are the shipped policy; tests lower
/// `max_hops` and cadence to keep a trace short.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TraceConfig {
    /// Master switch; also requires the server-leg prober to be enabled.
    pub enabled: bool,
    /// Maximum TTLs sent. Clamped to [`MAX_HOPS`].
    pub max_hops: u8,
    /// Probes per TTL. A second one is only sent after a timeout.
    pub probes_per_hop: u8,
    /// Cadence per active server.
    pub trace_interval: Duration,
    /// How long a completed trace stays reportable.
    pub cache_ttl: Duration,
    /// Global traces-per-minute cap.
    pub max_traces_per_minute: u32,
}

impl Default for TraceConfig {
    fn default() -> Self {
        Self {
            enabled: true,
            max_hops: MAX_HOPS,
            probes_per_hop: PROBES_PER_HOP,
            trace_interval: TRACE_INTERVAL,
            cache_ttl: TRACE_CACHE_TTL,
            max_traces_per_minute: MAX_TRACES_PER_MINUTE,
        }
    }
}

/// One injectable TTL prober, so the trace algorithm is unit-tested without a
/// network.
pub trait HopProber {
    /// Send one probe to `target` with the given IP TTL.
    ///
    /// `attempt` is 0 for the first probe at that TTL and 1 for the retry; a
    /// prober that ignores it is still correct.
    fn probe(&mut self, target: Ipv4Addr, ttl: u8, attempt: u8) -> ProbeOutcome;
}

/// Run the TTL sweep and reduce it to a [`Trace`], or `None` when nothing
/// answered.
///
/// The algorithm is deliberately platform-independent so its two load-bearing
/// rules - the TTL increases by one per hop, and the **last** router to answer
/// wins - are testable on any host with a scripted prober. A trace ends at the
/// first destination answer, a budget denial, or [`TraceConfig::max_hops`]
/// (clamped to [`MAX_HOPS`]); silent hops are skipped but do not lower the
/// reported distance.
pub fn run_trace(
    prober: &mut dyn HopProber,
    target: Ipv4Addr,
    config: &TraceConfig,
) -> Option<Trace> {
    let max_hops = config.max_hops.min(MAX_HOPS);
    let attempts = config.probes_per_hop.max(1);
    let mut hops = 0u8;
    let mut last_hop: Option<Ipv4Addr> = None;
    let mut last_hop_rtt_us: Option<u32> = None;
    for ttl in 1..=max_hops {
        for attempt in 0..attempts {
            match prober.probe(target, ttl, attempt) {
                ProbeOutcome::Router { responder, rtt_us } => {
                    // A router address must itself be a public unicast address:
                    // a loopback/private responder is a local stack artifact or
                    // a forged answer, not a path anchor. A zero or absurd RTT
                    // is not a measurement.
                    if !is_probeable(responder) || rtt_us == 0 || rtt_us > MAX_LAST_HOP_RTT_US {
                        continue;
                    }
                    hops = ttl;
                    last_hop = Some(responder);
                    last_hop_rtt_us = Some(rtt_us);
                    // One answer identifies the hop; no retry is sent.
                    break;
                }
                ProbeOutcome::Destination => {
                    hops = ttl;
                    return Some(Trace {
                        hops,
                        // The last intermediate router remains the anchor: the
                        // destination is already known, the penultimate router
                        // is what places a hosting-network server.
                        last_hop,
                        last_hop_rtt_us,
                        complete: true,
                    });
                }
                ProbeOutcome::Timeout => {}
                ProbeOutcome::Denied => {
                    // A partial trace is not a measurement: the budget refusing
                    // the next probe is not evidence about the path. Callers
                    // count the denial and report nothing.
                    return None;
                }
            }
        }
    }
    (hops > 0).then_some(Trace {
        hops,
        last_hop,
        last_hop_rtt_us,
        complete: false,
    })
}

/// One injectable traceroute, charging each probe before it is sent.
///
/// The registry depends on this trait rather than the socket so cache, cadence,
/// caps and budget behaviour are tested against a scripted trace.
pub trait TraceProber: Send + Sync {
    /// Measure the path to `target`, charging every probe through `charge`
    /// before it is sent. The first refused charge ends the trace and yields
    /// `None`; every socket error degrades to `None`.
    fn trace(&self, target: Ipv4Addr, charge: &mut dyn FnMut(u64) -> bool) -> Option<Trace>;
}

/// The real traceroute: unprivileged UDP probes with an ICMP echo fallback on
/// Linux, unavailable elsewhere (the relay fleet is Linux; other hosts still
/// compile, and the algorithm above is fully tested there).
pub struct SystemTraceProber;

impl TraceProber for SystemTraceProber {
    fn trace(&self, target: Ipv4Addr, charge: &mut dyn FnMut(u64) -> bool) -> Option<Trace> {
        traceroute(target, charge)
    }
}

/// Measure the relay→server path to `target` with TTL-limited probes.
///
/// Each probe is charged through `charge` before it is sent; a refused charge
/// ends the trace. Returns `None` when nothing usable came back - ICMP blocked
/// by the destination, no error-queue support, a socket error - so every
/// failure mode degrades to "unavailable" rather than a fabricated hop. The
/// caller owns the target gate: only an address a live session already
/// forwards to may be passed here.
pub fn traceroute(target: Ipv4Addr, charge: &mut dyn FnMut(u64) -> bool) -> Option<Trace> {
    #[cfg(target_os = "linux")]
    {
        platform_traceroute(target, charge)
    }
    #[cfg(not(target_os = "linux"))]
    {
        let _ = (target, charge);
        None
    }
}

// ── Platform-independent wire helpers ──────────────────────────────
//
// The packet layout, checksum and ICMP classification are compiled and tested
// on every host; only the socket calls are Linux-only.

/// ICMP echo request type (RFC 792).
#[cfg(any(test, target_os = "linux"))]
const ICMP_ECHO_REQUEST: u8 = 8;

/// ICMP echo reply type (RFC 792).
#[cfg(any(test, target_os = "linux"))]
const ICMP_ECHO_REPLY: u8 = 0;

/// ICMP time exceeded (RFC 792), sent by a router when TTL hits zero.
#[cfg(any(test, target_os = "linux"))]
const ICMP_TIME_EXCEEDED: u8 = 11;

/// ICMP destination unreachable (RFC 792).
#[cfg(any(test, target_os = "linux"))]
const ICMP_DEST_UNREACH: u8 = 3;

/// ICMP port unreachable code: generated by the destination host itself.
#[cfg(any(test, target_os = "linux"))]
const ICMP_PORT_UNREACH: u8 = 3;

/// Build one ICMP echo request with the given sequence number.
///
/// No payload rides after the 8-byte header: the fallback probe must be as
/// neutral as the UDP one. The identifier is left zero because the kernel
/// rewrites it to the ping socket's port identifier on an unprivileged ICMP
/// socket; the checksum is computed here so the packet is well-formed for a
/// raw socket too.
#[cfg(any(test, target_os = "linux"))]
fn build_icmp_echo_request(seq: u16) -> [u8; 8] {
    let mut packet = [0u8; 8];
    packet[0] = ICMP_ECHO_REQUEST;
    packet[6..8].copy_from_slice(&seq.to_be_bytes());
    let sum = checksum(&packet);
    packet[2..4].copy_from_slice(&sum.to_be_bytes());
    packet
}

/// Whether `buf` is an ICMP echo reply carrying `seq`.
///
/// The parser skips an IPv4 header when one is present (a raw-socket shape, and
/// harmless to support), then requires the echo-reply type and this probe's
/// sequence so a stale or unrelated reply cannot be attributed to the probe.
#[cfg(any(test, target_os = "linux"))]
fn is_icmp_echo_reply(buf: &[u8], seq: u16) -> bool {
    let icmp = if buf.len() >= 20 && buf[0] >> 4 == 4 {
        let header_len = usize::from(buf[0] & 0x0f) * 4;
        if buf.len() < header_len + 8 {
            return false;
        }
        &buf[header_len..]
    } else {
        buf
    };
    icmp.len() >= 8 && icmp[0] == ICMP_ECHO_REPLY && u16::from_be_bytes([icmp[6], icmp[7]]) == seq
}

/// Internet checksum (RFC 1071), one's complement of the 16-bit ones-complement
/// sum.
#[cfg(any(test, target_os = "linux"))]
fn checksum(data: &[u8]) -> u16 {
    let mut sum: u32 = 0;
    let mut i = 0;
    while i + 2 <= data.len() {
        sum += u32::from(u16::from_be_bytes([data[i], data[i + 1]]));
        i += 2;
    }
    if i < data.len() {
        sum += u32::from(u16::from_be_bytes([data[i], 0]));
    }
    while sum >> 16 != 0 {
        sum = (sum & 0xffff) + (sum >> 16);
    }
    !(sum as u16)
}

/// Classify one ICMP message queued for a probe.
///
/// This is the whole error-queue semantics in one pure function, tested on
/// every host:
///
/// * a time-exceeded is the router at this TTL;
/// * a port-unreachable whose offender is the destination is the destination
///   answering - the trace reached it;
/// * any other unreachable is a router that stopped the probe (a path anchor,
///   not a completion);
/// * an unspecified offender is not usable and the probe counts as silent.
#[cfg(any(test, target_os = "linux"))]
fn classify_icmp_error(
    icmp_type: u8,
    icmp_code: u8,
    offender: Ipv4Addr,
    target: Ipv4Addr,
    rtt_us: u32,
) -> ProbeOutcome {
    if offender.is_unspecified() {
        return ProbeOutcome::Timeout;
    }
    match (icmp_type, icmp_code) {
        (ICMP_TIME_EXCEEDED, _) => ProbeOutcome::Router {
            responder: offender,
            rtt_us: rtt_us.max(1),
        },
        (ICMP_DEST_UNREACH, ICMP_PORT_UNREACH) if offender == target => ProbeOutcome::Destination,
        (ICMP_DEST_UNREACH, _) if is_probeable(offender) => ProbeOutcome::Router {
            responder: offender,
            rtt_us: rtt_us.max(1),
        },
        _ => ProbeOutcome::Timeout,
    }
}

// ── Linux socket layer ─────────────────────────────────────────────

/// Fixed local UDP port for probes: the IANA traceroute range, and a port no
/// game server uses for gameplay, so an empty datagram cannot arrive at a live
/// game socket by accident.
#[cfg(target_os = "linux")]
const TRACE_UDP_PORT: u16 = 33_434;

/// Socket receive buffer for one datagram / one error-queue read.
#[cfg(target_os = "linux")]
const TRACE_RECV_BUFFER: usize = 1_500;

/// Ancillary-data buffer for one `IP_RECVERR` control message:
/// `sock_extended_err` (16 B) + offender `sockaddr_in` (16 B) + header.
#[cfg(target_os = "linux")]
const TRACE_CONTROL_BUFFER: usize = 128;

/// Run the real sweep with the platform probe, charging every probe.
#[cfg(target_os = "linux")]
fn platform_traceroute(target: Ipv4Addr, charge: &mut dyn FnMut(u64) -> bool) -> Option<Trace> {
    struct Sockets<'a> {
        charge: &'a mut dyn FnMut(u64) -> bool,
    }
    impl HopProber for Sockets<'_> {
        fn probe(&mut self, target: Ipv4Addr, ttl: u8, attempt: u8) -> ProbeOutcome {
            let _ = attempt;
            if !(self.charge)(PROBE_EGRESS_BYTES) {
                return ProbeOutcome::Denied;
            }
            linux::probe(target, ttl)
        }
    }
    run_trace(&mut Sockets { charge }, target, &TraceConfig::default())
}

#[cfg(target_os = "linux")]
mod linux {
    //! The unprivileged sockets. `libc` is already a proxy dependency on Linux,
    //! so this adds no crate and needs no capability: neither path opens a raw
    //! socket.

    use std::io;
    use std::net::Ipv4Addr;
    use std::time::Instant;

    use super::{
        build_icmp_echo_request, classify_icmp_error, is_icmp_echo_reply, ProbeOutcome,
        HOP_TIMEOUT, TRACE_CONTROL_BUFFER, TRACE_PROBE_PAYLOAD, TRACE_RECV_BUFFER, TRACE_UDP_PORT,
    };

    /// One probe with the UDP mechanism, falling back to ICMP echo when the UDP
    /// error queue cannot be used in this environment.
    pub(super) fn probe(target: Ipv4Addr, ttl: u8) -> ProbeOutcome {
        match udp_probe(target, ttl) {
            Some(outcome) => outcome,
            None => icmp_probe(target, ttl).unwrap_or(ProbeOutcome::Timeout),
        }
    }

    /// Whether the UDP error queue was usable; `None` means "fall back".
    fn udp_probe(target: Ipv4Addr, ttl: u8) -> Option<ProbeOutcome> {
        let fd = open_socket(libc::IPPROTO_UDP)?;
        let outcome = udp_probe_fd(fd, target, ttl);
        unsafe {
            libc::close(fd);
        }
        outcome
    }

    fn udp_probe_fd(fd: libc::c_int, target: Ipv4Addr, ttl: u8) -> Option<ProbeOutcome> {
        if !set_receive_error_queue(fd, ttl) || !connect(fd, target, TRACE_UDP_PORT) {
            return None;
        }
        let sent_at = Instant::now();
        let sent = unsafe {
            libc::send(
                fd,
                TRACE_PROBE_PAYLOAD.as_ptr().cast(),
                TRACE_PROBE_PAYLOAD.len(),
                0,
            )
        };
        if sent < 0 {
            // The probe never left; this is a setup/routing failure, so try the
            // ICMP fallback rather than calling the destination silent.
            return None;
        }
        Some(wait_for_icmp(fd, target, sent_at, Mode::Udp))
    }

    /// The ICMP echo fallback used when the UDP error queue is unavailable.
    /// `None` means the fallback itself could not be set up.
    fn icmp_probe(target: Ipv4Addr, ttl: u8) -> Option<ProbeOutcome> {
        let fd = open_socket(libc::IPPROTO_ICMP)?;
        let outcome = icmp_probe_fd(fd, target, ttl);
        unsafe {
            libc::close(fd);
        }
        outcome
    }

    fn icmp_probe_fd(fd: libc::c_int, target: Ipv4Addr, ttl: u8) -> Option<ProbeOutcome> {
        if !set_receive_error_queue(fd, ttl) || !bind_any(fd) || !connect(fd, target, 0) {
            return None;
        }
        // The kernel rewrites the echo identifier to the socket's port id on an
        // unprivileged ping socket and computes the checksum, so the header the
        // user fills in need only carry type and sequence.
        let seq = u16::from(ttl);
        let packet = build_icmp_echo_request(seq);
        let sent_at = Instant::now();
        let sent = unsafe { libc::send(fd, packet.as_ptr().cast(), packet.len(), 0) };
        if sent < 0 {
            return None;
        }
        Some(wait_for_icmp(fd, target, sent_at, Mode::Icmp { seq }))
    }

    /// Whether a normal (non-error-queue) datagram is expected on this socket.
    #[derive(Clone, Copy)]
    enum Mode {
        /// UDP: any datagram arriving on the connected socket came from the
        /// destination, which is a positive completion signal.
        Udp,
        /// ICMP echo: only an echo reply with this sequence completes a trace.
        Icmp { seq: u16 },
    }

    /// One non-blocking socket, `IP_TTL` set by the caller's helper.
    fn open_socket(protocol: libc::c_int) -> Option<libc::c_int> {
        let fd = unsafe {
            libc::socket(
                libc::AF_INET,
                libc::SOCK_DGRAM | libc::SOCK_CLOEXEC | libc::SOCK_NONBLOCK,
                protocol,
            )
        };
        (fd >= 0).then_some(fd)
    }

    /// Enable `IP_RECVERR` and set the probe TTL in one place: both are required
    /// for the mechanism, so a failure means "fall back".
    fn set_receive_error_queue(fd: libc::c_int, ttl: u8) -> bool {
        set_int_option(fd, libc::IP_RECVERR, 1)
            && set_int_option(fd, libc::IP_TTL, libc::c_int::from(ttl))
    }

    fn set_int_option(fd: libc::c_int, option: libc::c_int, value: libc::c_int) -> bool {
        unsafe {
            libc::setsockopt(
                fd,
                libc::IPPROTO_IP,
                option,
                (&value as *const libc::c_int).cast(),
                std::mem::size_of::<libc::c_int>() as libc::socklen_t,
            ) == 0
        }
    }

    /// Connect the probe socket to `target[:port]`, so the kernel routes the
    /// destination's ICMP errors to it.
    fn connect(fd: libc::c_int, target: Ipv4Addr, port: u16) -> bool {
        let mut destination: libc::sockaddr_in = unsafe { std::mem::zeroed() };
        destination.sin_family = libc::AF_INET as libc::sa_family_t;
        destination.sin_port = port.to_be();
        destination.sin_addr.s_addr = u32::from_ne_bytes(target.octets());
        unsafe {
            libc::connect(
                fd,
                (&destination as *const libc::sockaddr_in).cast(),
                std::mem::size_of::<libc::sockaddr_in>() as libc::socklen_t,
            ) == 0
        }
    }

    /// Bind the ICMP fallback socket to an ephemeral local port.
    ///
    /// The ping socket's identifier is its local port: the kernel fills the
    /// echo request's identifier from it and matches the reply against it, so
    /// the port must be allocated before the first send. (The UDP path gets an
    /// ephemeral port from `connect`; the ping path has no equivalent.)
    fn bind_any(fd: libc::c_int) -> bool {
        let mut local: libc::sockaddr_in = unsafe { std::mem::zeroed() };
        local.sin_family = libc::AF_INET as libc::sa_family_t;
        local.sin_port = 0;
        local.sin_addr.s_addr = 0;
        unsafe {
            libc::bind(
                fd,
                (&local as *const libc::sockaddr_in).cast(),
                std::mem::size_of::<libc::sockaddr_in>() as libc::socklen_t,
            ) == 0
        }
    }

    /// Wait up to [`HOP_TIMEOUT`] for the error queue (or a reply), polling so
    /// both paths are observed without a blocking-read race.
    fn wait_for_icmp(
        fd: libc::c_int,
        target: Ipv4Addr,
        sent_at: Instant,
        mode: Mode,
    ) -> ProbeOutcome {
        let mut buffer = [0u8; TRACE_RECV_BUFFER];
        loop {
            let elapsed = sent_at.elapsed();
            if elapsed >= HOP_TIMEOUT {
                return ProbeOutcome::Timeout;
            }
            let remaining_ms =
                (HOP_TIMEOUT - elapsed).as_millis().min(i32::MAX as u128) as libc::c_int;
            let mut polled = libc::pollfd {
                fd,
                events: libc::POLLIN | libc::POLLERR,
                revents: 0,
            };
            let ready = unsafe { libc::poll(&mut polled, 1, remaining_ms) };
            if ready < 0 {
                if io::Error::last_os_error().kind() == io::ErrorKind::Interrupted {
                    continue;
                }
                return ProbeOutcome::Timeout;
            }
            if ready == 0 {
                return ProbeOutcome::Timeout;
            }
            let rtt_us = sent_at.elapsed().as_micros().min(u128::from(u32::MAX)) as u32;

            if let Some(error) = read_icmp_error(fd) {
                return classify_icmp_error(
                    error.icmp_type,
                    error.icmp_code,
                    error.offender,
                    target,
                    rtt_us,
                );
            }

            match mode {
                Mode::Udp => {
                    // Any datagram on the connected socket is from the
                    // destination: it answered, so the trace is complete. The
                    // payload is deliberately not parsed - it is never game
                    // traffic, and nothing here interprets it.
                    if read_datagram(fd, &mut buffer).is_some() {
                        return ProbeOutcome::Destination;
                    }
                }
                Mode::Icmp { seq } => {
                    if let Some(received) = read_datagram(fd, &mut buffer) {
                        if is_icmp_echo_reply(&buffer[..received], seq) {
                            return ProbeOutcome::Destination;
                        }
                    }
                }
            }
        }
    }

    /// One ICMP error from the socket error queue.
    struct IcmpError {
        icmp_type: u8,
        icmp_code: u8,
        offender: Ipv4Addr,
    }

    /// Read one queued `IP_RECVERR` error. The kernel reports the router that
    /// generated it as the offender address in the same control message -
    /// not the probed destination - which is exactly the hop we want.
    fn read_icmp_error(fd: libc::c_int) -> Option<IcmpError> {
        let mut datagram = [0u8; 8];
        let mut control = [0u8; TRACE_CONTROL_BUFFER];
        let mut offender_address: libc::sockaddr_in = unsafe { std::mem::zeroed() };
        let mut iov = libc::iovec {
            iov_base: datagram.as_mut_ptr().cast(),
            iov_len: datagram.len(),
        };
        let mut message: libc::msghdr = unsafe { std::mem::zeroed() };
        message.msg_name = (&mut offender_address as *mut libc::sockaddr_in).cast();
        message.msg_namelen = std::mem::size_of::<libc::sockaddr_in>() as libc::socklen_t;
        message.msg_iov = &mut iov;
        message.msg_iovlen = 1;
        message.msg_control = control.as_mut_ptr().cast();
        message.msg_controllen = control.len();
        let received =
            unsafe { libc::recvmsg(fd, &mut message, libc::MSG_ERRQUEUE | libc::MSG_DONTWAIT) };
        if received < 0 {
            return None;
        }
        // The payload may be zero bytes (an empty UDP probe quotes nothing),
        // but the control message is what carries the answer.
        let needed = unsafe {
            libc::CMSG_LEN(
                (std::mem::size_of::<libc::sock_extended_err>()
                    + std::mem::size_of::<libc::sockaddr_in>()) as libc::c_uint,
            ) as usize
        };
        let mut control_message = unsafe { libc::CMSG_FIRSTHDR(&message) };
        while !control_message.is_null() {
            let header = unsafe { &*control_message };
            if header.cmsg_level == libc::IPPROTO_IP
                && header.cmsg_type == libc::IP_RECVERR
                && (header.cmsg_len as usize) >= needed
                && message.msg_flags & libc::MSG_CTRUNC == 0
            {
                let data = unsafe { libc::CMSG_DATA(control_message) };
                let extended =
                    unsafe { std::ptr::read_unaligned(data.cast::<libc::sock_extended_err>()) };
                if extended.ee_origin == libc::SO_EE_ORIGIN_ICMP {
                    // ip_recv_error appends the offender sockaddr_in to the
                    // sock_extended_err in the same control message.
                    let offender = unsafe {
                        std::ptr::read_unaligned(
                            data.add(std::mem::size_of::<libc::sock_extended_err>())
                                .cast::<libc::sockaddr_in>(),
                        )
                    };
                    return Some(IcmpError {
                        icmp_type: extended.ee_type,
                        icmp_code: extended.ee_code,
                        offender: ipv4_from(offender.sin_addr.s_addr),
                    });
                }
            }
            control_message = unsafe { libc::CMSG_NXTHDR(&message, control_message) };
        }
        None
    }

    /// One ordinary datagram read; `None` for "nothing pending" and for any
    /// socket error (a UDP socket reports `ECONNREFUSED` here once the error
    /// queue has been consumed).
    fn read_datagram(fd: libc::c_int, buffer: &mut [u8]) -> Option<usize> {
        let received = unsafe {
            libc::recv(
                fd,
                buffer.as_mut_ptr().cast(),
                buffer.len(),
                libc::MSG_DONTWAIT,
            )
        };
        usize::try_from(received).ok()
    }

    fn ipv4_from(network_order: u32) -> Ipv4Addr {
        Ipv4Addr::from(u32::from_be(network_order))
    }

    /// Whether the last probe could even be attempted. Kept for tests that
    /// check the egress charge equals the wire size bound.
    #[cfg(test)]
    pub(super) fn charge_bytes() -> u64 {
        super::PROBE_EGRESS_BYTES
    }
}

// ── Registry: cache, cadence, caps, budget, reporting ──────────────

/// One server's cached trace.
#[derive(Debug, Clone, Copy)]
struct CachedTrace {
    trace: Trace,
    measured_at: Instant,
}

/// One live data-plane session's interest in its game server's path.
#[derive(Debug, Clone, Copy)]
struct Interest {
    /// Client IP (diagnostics and pruning only; routing is by session token).
    #[allow(dead_code)]
    client_ip: Ipv4Addr,
    /// The game server this session forwards to.
    server: Ipv4Addr,
    /// Last forward that refreshed this interest.
    last_seen: Instant,
    /// When this session was last sent a trace, for [`REPORT_INTERVAL`].
    last_report: Option<Instant>,
}

/// What one trace tick did, for tests and tracing.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct TraceTick {
    /// Traces started this tick.
    pub traces: u64,
    /// Probes actually sent across those traces.
    pub probes: u64,
    /// Traces that produced no usable path.
    pub unavailable: u64,
    /// Due servers left untraced because the global cap applied.
    pub skipped: u64,
    /// Traces cut short because the egress budget refused a probe.
    pub denied: u64,
}

struct Inner {
    /// Active interests keyed by data-plane session token.
    interests: HashMap<u32, Interest>,
    /// Latest trace per game server.
    cached: HashMap<Ipv4Addr, CachedTrace>,
    /// When each server was last attempted, successful or not.
    last_attempt: HashMap<Ipv4Addr, Instant>,
    /// Start of the current one-minute global-budget window.
    budget_start: Instant,
    /// Traces started in the current budget window.
    budget_used: u32,
    /// Lifetime counters, mirrored into [`ProxyMetrics`] when one is attached.
    traces_started: u64,
    probes: u64,
    unavailable: u64,
    skipped: u64,
    budget_denied: u64,
}

/// The relay-wide traceroute registry: per-server cache, global cap, and the
/// interest map the data path and the control plane share.
pub struct TraceRegistry {
    config: TraceConfig,
    clock: Arc<dyn Clock>,
    prober: Arc<dyn TraceProber>,
    metrics: Option<Arc<ProxyMetrics>>,
    /// Optional egress budget guard; every probe is charged through it.
    budget: Option<Arc<BudgetGuard>>,
    inner: Mutex<Inner>,
}

impl TraceRegistry {
    /// Build a registry over the injected prober and clock.
    pub fn new(config: TraceConfig, clock: Arc<dyn Clock>, prober: Arc<dyn TraceProber>) -> Self {
        let budget_start = clock.now();
        Self {
            config,
            clock,
            prober,
            metrics: None,
            budget: None,
            inner: Mutex::new(Inner {
                interests: HashMap::new(),
                cached: HashMap::new(),
                last_attempt: HashMap::new(),
                budget_start,
                budget_used: 0,
                traces_started: 0,
                probes: 0,
                unavailable: 0,
                skipped: 0,
                budget_denied: 0,
            }),
        }
    }

    /// Attach the process metrics collector.
    pub fn with_metrics(mut self, metrics: Arc<ProxyMetrics>) -> Self {
        self.metrics = Some(metrics);
        self
    }

    /// Attach the relay's egress budget guard: probe egress is then charged
    /// through the same ceiling as relayed traffic.
    pub fn with_budget(mut self, budget: Arc<BudgetGuard>) -> Self {
        self.budget = Some(budget);
        self
    }

    /// Whether tracing is enabled for this relay.
    pub fn enabled(&self) -> bool {
        self.config.enabled
    }

    fn lock(&self) -> MutexGuard<'_, Inner> {
        self.inner
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    /// Register or refresh a session's interest in tracing `server`.
    ///
    /// Called by the data path under the same rules as the server-leg prober:
    /// only an address this session has already forwarded
    /// [`FORWARD_THRESHOLD`] packets to, only a public unicast address, and the
    /// threshold is enforced here too rather than only at the call site.
    pub fn note_forward(&self, token: u32, client_ip: Ipv4Addr, server: Ipv4Addr, forwarded: u64) {
        if !self.config.enabled {
            self.count_skip();
            return;
        }
        if forwarded < FORWARD_THRESHOLD {
            return;
        }
        if !is_probeable(server) {
            self.count_skip();
            return;
        }
        let now = self.clock.now();
        let mut inner = self.lock();
        if !inner.interests.contains_key(&token) && inner.interests.len() >= MAX_INTERESTS {
            inner.skipped += 1;
            return;
        }
        inner
            .interests
            .entry(token)
            .and_modify(|interest| {
                interest.client_ip = client_ip;
                interest.server = server;
                interest.last_seen = now;
            })
            .or_insert(Interest {
                client_ip,
                server,
                last_seen: now,
                last_report: None,
            });
    }

    /// Run one trace tick: prune dead interests, then start at most one due
    /// trace within the global cap.
    ///
    /// The probe runs synchronously on the calling thread; the production
    /// caller is the dedicated trace thread, so a path that never answers costs
    /// the hop timeouts and never an async worker.
    pub fn probe_due(&self) -> TraceTick {
        let mut tick = TraceTick::default();
        if !self.config.enabled {
            return tick;
        }
        let now = self.clock.now();
        let due = {
            let mut inner = self.lock();
            inner.prune(now);
            inner.due_servers(now, &self.config)
        };
        let mut started = false;
        for server in due {
            let proceed = {
                let mut inner = self.lock();
                inner.refill_budget(now);
                if !started && inner.budget_used < self.config.max_traces_per_minute {
                    inner.budget_used += 1;
                    inner.last_attempt.insert(server, now);
                    true
                } else {
                    inner.skipped += 1;
                    tick.skipped += 1;
                    false
                }
            };
            if !proceed {
                continue;
            }
            started = true;
            tick.traces += 1;

            let mut probes = 0u64;
            let mut denied = false;
            let mut charge = |bytes: u64| {
                if let Some(budget) = &self.budget {
                    let data_used = self
                        .metrics
                        .as_ref()
                        .map_or(0, |metrics| metrics.bytes_relayed.load(Ordering::Relaxed));
                    if !budget.try_charge_probe(
                        data_used,
                        bytes,
                        crate::budget::current_month_key(),
                    ) {
                        denied = true;
                        return false;
                    }
                }
                probes += 1;
                true
            };
            let trace = self.prober.trace(server, &mut charge);
            tick.probes += probes;

            let mut inner = self.lock();
            inner.traces_started += 1;
            inner.probes += probes;
            if denied {
                tick.denied += 1;
                inner.budget_denied += 1;
                // A partial trace is not a measurement: the refusal is not
                // evidence about the path, so nothing is cached or reported.
                continue;
            }
            match trace.and_then(sanitize_trace) {
                Some(trace) => {
                    if inner.cached.len() >= MAX_TRACE_SERVERS
                        && !inner.cached.contains_key(&server)
                    {
                        if let Some(stalest) = inner
                            .cached
                            .iter()
                            .min_by_key(|(_, cached)| cached.measured_at)
                            .map(|(server, _)| *server)
                        {
                            inner.cached.remove(&stalest);
                        }
                    }
                    inner.cached.insert(
                        server,
                        CachedTrace {
                            trace,
                            measured_at: now,
                        },
                    );
                }
                None => {
                    tick.unavailable += 1;
                    inner.unavailable += 1;
                }
            }
        }

        let counters = {
            let inner = self.lock();
            (
                inner.traces_started,
                inner.probes,
                inner.unavailable,
                inner.skipped,
                inner.budget_denied,
            )
        };
        if let Some(metrics) = &self.metrics {
            metrics.set_server_trace_counters(
                counters.0, counters.1, counters.2, counters.3, counters.4,
            );
        }
        tick
    }

    /// Reports that are due to be pushed to their control sessions.
    ///
    /// One [`ControlMessage::ServerTrace`] per session per [`REPORT_INTERVAL`],
    /// only while the cached trace is younger than the configured cache TTL.
    /// The message carries the age at send time, so the client can refuse a
    /// stale figure even if the push is delayed.
    pub fn due_pushes(&self) -> Vec<(u32, ControlMessage)> {
        if !self.config.enabled {
            return Vec::new();
        }
        let now = self.clock.now();
        let mut inner = self.lock();
        let cache_ttl = self.config.cache_ttl;
        let mut pushes = Vec::new();
        let tokens: Vec<u32> = inner.interests.keys().copied().collect();
        for token in tokens {
            let Some(interest) = inner.interests.get(&token).copied() else {
                continue;
            };
            let Some(cached) = inner.cached.get(&interest.server).copied() else {
                continue;
            };
            let age = now.saturating_duration_since(cached.measured_at);
            if age > cache_ttl
                || interest
                    .last_report
                    .is_some_and(|last| now.saturating_duration_since(last) < REPORT_INTERVAL)
            {
                continue;
            }
            let (last_hop, last_hop_rtt_us) = match cached.trace.last_hop {
                Some(last_hop) => (last_hop, cached.trace.last_hop_rtt_us.unwrap_or(0)),
                None => (Ipv4Addr::UNSPECIFIED, 0),
            };
            if let Some(entry) = inner.interests.get_mut(&token) {
                entry.last_report = Some(now);
                pushes.push((
                    token,
                    ControlMessage::ServerTrace {
                        server: interest.server,
                        hops: cached.trace.hops,
                        last_hop,
                        last_hop_rtt_us,
                        flags: if cached.trace.complete {
                            trace_flags::COMPLETE
                        } else {
                            0
                        },
                        age_ms: age.as_millis().min(u128::from(u16::MAX)) as u16,
                    },
                ));
            }
        }
        pushes
    }

    /// The cached trace for `server`, if it is still inside the cache TTL.
    /// Exposed for the relay's diagnostics and tests.
    pub fn cached_trace(&self, server: Ipv4Addr) -> Option<Trace> {
        let now = self.clock.now();
        let inner = self.lock();
        inner
            .cached
            .get(&server)
            .filter(|cached| {
                now.saturating_duration_since(cached.measured_at) <= self.config.cache_ttl
            })
            .map(|cached| cached.trace)
    }

    /// Number of live interests (tests and diagnostics).
    pub fn interest_count(&self) -> usize {
        self.lock().interests.len()
    }

    /// Lifetime traces started.
    pub fn trace_count(&self) -> u64 {
        self.lock().traces_started
    }

    /// Lifetime probes actually sent.
    pub fn probe_count(&self) -> u64 {
        self.lock().probes
    }

    /// Lifetime traces that produced no usable path.
    pub fn unavailable_count(&self) -> u64 {
        self.lock().unavailable
    }

    /// Lifetime skipped trace opportunities (cap, refused address, disabled).
    pub fn skip_count(&self) -> u64 {
        self.lock().skipped
    }

    /// Lifetime traces cut short by an egress-budget refusal.
    pub fn budget_denied_count(&self) -> u64 {
        self.lock().budget_denied
    }

    /// Attach the trace thread to `Arc<Self>`; returns `None` when tracing is
    /// disabled. The thread runs for the process lifetime.
    pub fn spawn_prober(self: Arc<Self>) -> Option<std::thread::JoinHandle<()>> {
        if !self.enabled() {
            return None;
        }
        std::thread::Builder::new()
            .name("server-trace-prober".to_string())
            .spawn(move || loop {
                self.probe_due();
                std::thread::sleep(TRACE_TICK);
            })
            .ok()
    }

    fn count_skip(&self) {
        self.lock().skipped += 1;
    }
}

/// Reject a trace that violates the relay's own bounds before it is cached.
///
/// The socket layer already filters per hop, but the registry is the last place
/// before a report, so a scripted or future prober cannot smuggle an out-of-
/// bounds hop count, a private router or an absurd RTT into the wire.
fn sanitize_trace(trace: Trace) -> Option<Trace> {
    if trace.hops == 0 || trace.hops > MAX_HOPS {
        return None;
    }
    match (trace.last_hop, trace.last_hop_rtt_us) {
        (None, None) => {}
        (Some(last_hop), Some(rtt_us))
            if is_probeable(last_hop) && rtt_us > 0 && rtt_us <= MAX_LAST_HOP_RTT_US => {}
        _ => return None,
    }
    Some(trace)
}

impl Inner {
    /// Drop interests with no forward inside [`INTEREST_TTL`], then drop the
    /// per-server state nothing references any more so the maps stay bounded by
    /// the live session set rather than by every server ever seen.
    fn prune(&mut self, now: Instant) {
        let ttl = INTEREST_TTL;
        self.interests
            .retain(|_, interest| now.saturating_duration_since(interest.last_seen) <= ttl);
        let live: std::collections::HashSet<Ipv4Addr> = self
            .interests
            .values()
            .map(|interest| interest.server)
            .collect();
        self.cached.retain(|server, _| live.contains(server));
        self.last_attempt.retain(|server, _| live.contains(server));
    }

    /// Servers due for a trace: never attempted, or last attempted at least the
    /// cadence ago. Deduplicated, so a hundred sessions naming one server still
    /// cost one trace.
    fn due_servers(&self, now: Instant, config: &TraceConfig) -> Vec<Ipv4Addr> {
        let mut servers: Vec<Ipv4Addr> = self
            .interests
            .values()
            .filter(|interest| is_probeable(interest.server))
            .map(|interest| interest.server)
            .collect();
        servers.sort_unstable();
        servers.dedup();
        servers.retain(|server| {
            let Some(last) = self.last_attempt.get(server) else {
                return true;
            };
            now.saturating_duration_since(*last) >= config.trace_interval
        });
        servers
    }

    /// Refill the per-minute trace budget if the window elapsed.
    fn refill_budget(&mut self, now: Instant) {
        if now.saturating_duration_since(self.budget_start) >= Duration::from_secs(60) {
            self.budget_start = now;
            self.budget_used = 0;
        }
    }
}

