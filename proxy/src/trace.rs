    struct ScriptedTraceProber {
        traces: Mutex<VecDeque<Option<Trace>>>,
        calls: AtomicUsize,
        probes_per_call: u64,
        denials: AtomicU64,
    }

    impl ScriptedTraceProber {
        fn new(traces: Vec<Option<Trace>>) -> Self {
            Self {
                traces: Mutex::new(traces.into()),
                calls: AtomicUsize::new(0),
                probes_per_call: 3,
                denials: AtomicU64::new(0),
            }
        }

        fn calls(&self) -> usize {
            self.calls.load(Ordering::Relaxed)
        }
    }

    impl TraceProber for ScriptedTraceProber {
        fn trace(&self, _target: Ipv4Addr, charge: &mut dyn FnMut(u64) -> bool) -> Option<Trace> {
            self.calls.fetch_add(1, Ordering::Relaxed);
            for _ in 0..self.probes_per_call {
                if !charge(PROBE_EGRESS_BYTES) {
                    self.denials.fetch_add(1, Ordering::Relaxed);
                    return None;
                }
            }
            self.traces
                .lock()
                .expect("script")
                .pop_front()
                .unwrap_or(None)
        }
    }

    fn trace_at(hops: u8, last: u8, rtt_us: u32, complete: bool) -> Trace {
        Trace {
            hops,
            last_hop: Some(Ipv4Addr::new(91, 199, 82, last)),
            last_hop_rtt_us: Some(rtt_us),
            complete,
        }
    }

    fn server(last: u8) -> Ipv4Addr {
        Ipv4Addr::new(91, 199, 82, last)
    }

